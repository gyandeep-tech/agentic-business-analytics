import json

from langchain_core.tools import tool

from analytics.anomaly_tools import get_anomaly_summary


@tool
def get_anomaly_detection_summary() -> str:
    """
    Analyze monthly sales anomaly detection results.

    Returns:
    - Total months analyzed
    - Number of anomalous months
    - Number of normal months
    - Percentage of months flagged as anomalies
    - Highest-revenue anomaly
    - Lowest-revenue anomaly
    - Detailed information about every detected anomaly

    The results come from the deterministic anomaly detection
    output generated by the analytics pipeline.
    """

    result = get_anomaly_summary()

    return json.dumps(
        result,
        default=str
    )