import json

from langchain_core.tools import tool

from analytics.forecast_tools import get_revenue_forecast_summary


@tool
def get_revenue_forecast() -> str:
    """
    Analyze the revenue forecast generated by the forecasting model.

    Returns:
    - Number of forecast months
    - Total forecast revenue
    - Average forecast revenue
    - Highest forecast month
    - Lowest forecast month
    - First forecast month
    - Last forecast month
    - First-to-last forecast period growth
    - Individual monthly forecast values

    The forecast values are read from the processed
    revenue_forecast.csv file.
    """

    result = get_revenue_forecast_summary()

    return json.dumps(
        result,
        default=str
    )