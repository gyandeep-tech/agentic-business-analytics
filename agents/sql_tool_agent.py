# =========================================================
# SQL TOOL AGENT
# =========================================================

def ask_sql_agent(question: str):

    messages = [
        ("system", SYSTEM_PROMPT),
        ("human", question)
    ]

    max_attempts = 5
    sql_queries = []
    sql_results = []

    print("\n" + "=" * 70)
    print("SQL AGENT STARTED")
    print("=" * 70)

    print("\nUser Question:")
    print(question)

    for attempt in range(1, max_attempts + 1):

        print("\n" + "-" * 70)
        print(f"AGENT ATTEMPT: {attempt}")
        print("-" * 70)

        # =================================================
        # LLM CALL
        # =================================================

        try:

            response = llm_with_tools.invoke(messages)

        except RateLimitError:

            print("\n[WARNING] Groq rate limit reached.")
            print("[INFO] Waiting 2 seconds before retrying...")

            time.sleep(2)

            response = llm_with_tools.invoke(messages)

        # =================================================
        # CHECK FOR TOOL CALL
        # =================================================

        if not response.tool_calls:

            print("\n" + "=" * 70)
            print("FINAL ANSWER")
            print("=" * 70)

            print(response.content)

            print("\n" + "=" * 70)
            print("SQL AGENT FINISHED")
            print("=" * 70)

            return {
                "question": question,
                "answer": response.content,
                "sql_queries": sql_queries,
                "sql_results": sql_results,
                "tool_called": len(sql_queries) > 0,
                "attempts": attempt
}

        # =================================================
        # ASSISTANT TOOL CALL
        # =================================================

        messages.append(response)

        execution_failed = False

        # =================================================
        # EXECUTE TOOLS
        # =================================================

        for tool_call in response.tool_calls:

            tool_name = tool_call["name"]
            tool_args = tool_call["args"]
            tool_call_id = tool_call["id"]

            print("\n[TOOL CALL]")
            print(f"Tool: {tool_name}")

            print("\n[SQL GENERATED]")

            sql_query = tool_args.get("sql", "")

            print(sql_query)

            sql_queries.append(sql_query)

            # -------------------------------------------------
            # EXECUTE TOOL
            # -------------------------------------------------

            try:

                if tool_name == "execute_sql":

                    tool_result = execute_sql.invoke(tool_args)

                    print("\n[SQL RESULT]")

                    print(tool_result)

                    sql_results.append(tool_result)

                    messages.append(
                        ToolMessage(
                            content=str(tool_result),
                            tool_call_id=tool_call_id
                        )
                    )

                else:

                    raise ValueError(
                        f"Unknown tool requested: {tool_name}"
                    )

            # -------------------------------------------------
            # TOOL ERROR
            # -------------------------------------------------

            except Exception as error:

                execution_failed = True

                print("\n[SQL ERROR]")
                print(error)

                error_message = (
                    "SQL execution failed.\n"
                    f"Database error: {error}\n\n"
                    "Review the database schema and correct the SQL query. "
                    "Do not repeat the same invalid SQL."
                )

                messages.append(
                    ToolMessage(
                        content=error_message,
                        tool_call_id=tool_call_id
                    )
                )

        # =================================================
        # RETRY AFTER SQL ERROR
        # =================================================

        if execution_failed:

            print("\n[INFO] SQL execution failed.")

            if attempt == max_attempts:

                raise RuntimeError(
                    "SQL Agent failed after maximum retry attempts."
                )

            print("[INFO] Asking the LLM to correct the SQL...")

            continue

        # =================================================
        # CONTINUE AGENT REASONING
        # =================================================

        print("\n[INFO] Tool execution successful.")
        print("[INFO] Continuing agent reasoning...")


    raise RuntimeError(
        "SQL Agent reached maximum reasoning/tool-call steps."
    )